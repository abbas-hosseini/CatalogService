-- CASE avoids H2 2.4.240's cross-session CHECK (IN ...) bug.
ALTER TABLE employees ADD CONSTRAINT chk_employee_gender
    CHECK (gender IS NULL OR CASE gender
        WHEN 'MALE' THEN TRUE
        WHEN 'FEMALE' THEN TRUE
        ELSE FALSE
    END);

