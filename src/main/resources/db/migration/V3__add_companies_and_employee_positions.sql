CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(2000)
);

CREATE TABLE employee_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    -- Existing assignments have no known company. The API requires one for new/edited positions.
    company_id BIGINT REFERENCES companies(id),
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    notes VARCHAR(2000),
    CONSTRAINT uq_employee_position UNIQUE (employee_id, company_id, job_id)
);

CREATE INDEX idx_employee_positions_company ON employee_positions(company_id);
CREATE INDEX idx_employee_positions_job ON employee_positions(job_id);

-- Preserve each existing assignment before removing the single-job relationship.
INSERT INTO employee_positions (employee_id, job_id)
SELECT id, job_id FROM employees WHERE job_id IS NOT NULL;

ALTER TABLE employees DROP COLUMN job_id;
