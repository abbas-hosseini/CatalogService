ALTER TABLE employee_scores ADD COLUMN strengths VARCHAR(5000);
ALTER TABLE employee_scores ADD COLUMN weaknesses VARCHAR(5000);

CREATE TABLE assessment_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score_id BIGINT NOT NULL REFERENCES employee_scores(id) ON DELETE CASCADE,
    file_name VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    content BYTEA NOT NULL
);
CREATE INDEX idx_assessment_attachment_score ON assessment_attachments(score_id);
