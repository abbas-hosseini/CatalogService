CREATE TABLE evaluation_factors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    parent_id BIGINT REFERENCES evaluation_factors(id),
    description VARCHAR(2000),
    CONSTRAINT factor_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    parent_id BIGINT REFERENCES jobs(id),
    description VARCHAR(2000),
    CONSTRAINT job_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnel_code VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    job_id BIGINT REFERENCES jobs(id),
    description VARCHAR(2000)
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    provider VARCHAR(160),
    duration_hours NUMERIC(8,2) NOT NULL CHECK (duration_hours > 0 AND duration_hours <= 10000),
    description VARCHAR(2000)
);

CREATE TABLE employee_trainings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    course_id BIGINT NOT NULL REFERENCES courses(id),
    completion_date DATE NOT NULL,
    score NUMERIC(5,2) CHECK (score BETWEEN 0 AND 100),
    certificate_number VARCHAR(100),
    notes VARCHAR(2000),
    CONSTRAINT uq_employee_course_date UNIQUE (employee_id, course_id, completion_date)
);

CREATE TABLE employee_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    factor_id BIGINT NOT NULL REFERENCES evaluation_factors(id),
    score NUMERIC(5,2) NOT NULL CHECK (score BETWEEN 0 AND 100),
    assessed_on DATE NOT NULL,
    notes VARCHAR(2000),
    CONSTRAINT uq_employee_factor UNIQUE (employee_id, factor_id)
);

CREATE TABLE job_requirements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES jobs(id),
    factor_id BIGINT NOT NULL REFERENCES evaluation_factors(id),
    minimum_score NUMERIC(5,2) NOT NULL CHECK (minimum_score BETWEEN 0 AND 100),
    notes VARCHAR(2000),
    CONSTRAINT uq_job_factor UNIQUE (job_id, factor_id)
);

CREATE INDEX idx_training_employee ON employee_trainings(employee_id);
CREATE INDEX idx_score_employee ON employee_scores(employee_id);
CREATE INDEX idx_requirement_job ON job_requirements(job_id);
